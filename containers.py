#!/usr/bin/env python3
"""
containers.py — emit containerized runners (Podman/Docker commands + K8s Jobs)
for the engine's staged methodology.

Authorized / lab / CTF use only.

This GENERATES launch specs the operator runs (`podman run …` / `kubectl apply
-f …`) so the full tool arsenal works reproducibly without host installs and can
scale on a cluster. The engine executes nothing here and ships no exploit
payloads — it packages the methodology it already stages. Image catalog lives in
docs/containers.md (knowledge-driven); falls back to the embedded defaults.
"""
from __future__ import annotations

import shlex
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor, as_completed

_FALLBACK = {
    "runtime": "podman",
    "network": "host",
    "default_image": "docker.io/kalilinux/kali-rolling",
    "images": {
        "nmap": "docker.io/instrumentisto/nmap",
        "nuclei": "docker.io/projectdiscovery/nuclei",
    },
}


def load_config(docs_dir=None):
    cfg = {**_FALLBACK, "images": dict(_FALLBACK["images"])}
    try:
        from knowledge_loader import load_knowledge
        c = load_knowledge(docs_dir).containers or {}
        for k, v in c.items():
            if k == "images" and isinstance(v, dict):
                cfg["images"].update(v)
            else:
                cfg[k] = v
    except Exception:                                                  # pragma: no cover
        pass
    return cfg


def _tool_of(command):
    cmd = (command or "").strip()
    if not cmd or cmd.startswith("#") or cmd.startswith("<"):
        return None                       # comment / placeholder step — not runnable
    tok = cmd.split()[0]
    return tok if tok[:1].isalpha() else None


def containerize(command, cfg=None, runtime=None, network=None):
    """Wrap one methodology command as a container run line (or None if not runnable)."""
    cfg = cfg or load_config()
    runtime = runtime or cfg.get("runtime", "podman")
    network = network or cfg.get("network", "host")
    tool = _tool_of(command)
    if not tool:
        return None
    img = cfg["images"].get(tool)
    if img:                               # dedicated image: entrypoint is the tool
        rest = command.split(None, 1)[1] if " " in command else ""
        return f"{runtime} run --rm --network={network} {img} {rest}".rstrip()
    # toolbox image: run the command through a shell
    return f"{runtime} run --rm --network={network} {cfg['default_image']} sh -lc {shlex.quote(command)}"


def k8s_job(check, module, cfg, idx):
    cmd = check.get("command", "")
    tool = _tool_of(cmd)
    if not tool:
        return None
    img = cfg["images"].get(tool)
    if img:
        container = {"name": tool[:60], "image": img, "args": shlex.split(cmd)[1:]}
    else:
        container = {"name": "tool", "image": cfg["default_image"], "command": ["sh", "-lc", cmd]}
    name = f"pe-{module.get('module', 'mod')}-{idx}"[:63].replace("_", "-")
    return {"apiVersion": "batch/v1", "kind": "Job",
            "metadata": {"name": name, "labels": {"app": "pentest-engine",
                                                   "module": module.get("module", "")}},
            "spec": {"backoffLimit": 0,
                     "template": {"spec": {"restartPolicy": "Never", "containers": [container]}}}}


_HEADER = ("Generated by the pentest engine. The OPERATOR runs these, in authorized "
           "scope.\nThe engine generated the launch specs; it executes nothing and ships "
           "no exploit payloads.")


def write_runner_script(modules, path, runtime="podman", cfg=None):
    cfg = cfg or load_config()
    out = ["#!/usr/bin/env bash", "# " + _HEADER.replace("\n", "\n# "), "set -u", ""]
    for m in modules:
        out.append(f"# === {m.get('title', m.get('module'))} — {m.get('target', '')} ===")
        for c in m.get("checks", []):
            run = containerize(c.get("command", ""), cfg, runtime)
            if run:
                out.append(f"#   {c.get('attack', '')}  {c.get('name', '')}")
                out.append(run)
        out.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")


def write_k8s_jobs(modules, path, cfg=None):
    import yaml
    cfg = cfg or load_config()
    docs, idx = [], 0
    for m in modules:
        for c in m.get("checks", []):
            spec = k8s_job(c, m, cfg, idx)
            if spec:
                docs.append(spec)
                idx += 1
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# " + _HEADER.replace("\n", "\n# ") + "\n")
        yaml.safe_dump_all(docs, fh, sort_keys=False)
    return idx


# --------------------------------------------------------------------------- #
# Containerized ENUMERATION executor (opt-in). Runs the non-exploit, NON-intrusive
# enumeration checks — the same category the engine already runs with nmap — inside
# containers. NEVER runs exploits or credential brute/spray (those are filtered out
# and stay staged for the operator). Caller must scope-gate first.
# --------------------------------------------------------------------------- #
def runnable_checks(modules):
    """Non-intrusive, actually-runnable enumeration checks from dispatched modules."""
    from modules import _is_intrusive
    out = []
    for m in modules:
        for c in m.get("checks", []):
            if _tool_of(c.get("command", "")) and not _is_intrusive(c):
                out.append({"module": m.get("module", ""), "name": c.get("name", ""),
                            "attack": c.get("attack", ""), "command": c.get("command", "")})
    return out


def _default_network(configured="host"):
    """--network=host is Linux-only; Docker Desktop / Podman machine on Windows
    & macOS reject it, so fall back to bridge there. An explicit non-host choice
    from config/knowledge is honored as-is."""
    if configured and configured != "host":
        return configured
    return "host" if sys.platform.startswith("linux") else "bridge"


def _run_one(ch, cfg, runtime, timeout, network=None):
    line = containerize(ch["command"], cfg, runtime, network)
    if not line:
        return None
    try:
        proc = subprocess.run(shlex.split(line), capture_output=True, text=True, timeout=timeout)
        return {**ch, "run": line, "rc": proc.returncode,
                "output": (proc.stdout or "") + (proc.stderr or "")}
    except subprocess.TimeoutExpired:
        return {**ch, "run": line, "rc": None, "output": "(timed out)"}
    except Exception as e:                                             # pragma: no cover
        return {**ch, "run": line, "rc": None, "output": f"(error: {e})"}


def run_enumeration(modules, cfg=None, runtime=None, timeout=300, workers=6, progress=None):
    """Execute the non-intrusive enumeration checks in containers, IN PARALLEL across
    `workers` threads (each task is its own container). Returns result dicts
    {module,name,attack,command,run,rc,output}. ENUMERATION only — exploits and
    credential attacks are excluded by runnable_checks(). Scope-gate upstream."""
    cfg = cfg or load_config()
    runtime = runtime or cfg.get("runtime", "podman")
    if shutil.which(runtime) is None:
        raise RuntimeError(f"{runtime} not found on PATH")
    net = _default_network(cfg.get("network", "host"))   # host on Linux, bridge on Win/macOS
    checks = runnable_checks(modules)
    results = []
    with ThreadPoolExecutor(max_workers=max(1, workers)) as ex:
        futures = {ex.submit(_run_one, ch, cfg, runtime, timeout, net): ch for ch in checks}
        for fut in as_completed(futures):
            ch = futures[fut]
            if progress:
                progress(f"[{ch['module']}] {ch['name']}")
            r = fut.result()
            if r:
                results.append(r)
    results.sort(key=lambda r: (r["module"], r["name"]))   # stable output despite parallelism
    return results


if __name__ == "__main__":
    import os
    if len(sys.argv) < 2:
        print("usage: python containers.py <nmap.xml> [podman|docker|kubernetes]"); sys.exit(1)
    from nmap_analyzer import load_scan, analyze, build_report
    from modules import dispatch
    hosts, meta, _ = load_scan(sys.argv[1])
    mods = dispatch(build_report(hosts, meta, analyze(hosts)))
    rt = sys.argv[2] if len(sys.argv) > 2 else "podman"
    out_dir = tempfile.gettempdir()
    if rt == "kubernetes":
        out = os.path.join(out_dir, "pe-jobs.yaml")
        write_k8s_jobs(mods, out); print("wrote " + out)
    else:
        out = os.path.join(out_dir, "pe-runners.sh")
        write_runner_script(mods, out, rt); print("wrote " + out)
